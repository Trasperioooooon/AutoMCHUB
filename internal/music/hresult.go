package music

import "fmt"

// HRError 表示某一步 COM 调用返回了失败的 HRESULT。
type HRError struct {
	Step string // 如「IAudioClient::Initialize」
	Code uint32
}

func (e *HRError) Error() string { return e.Step + " → " + HRText(e.Code) }

// HRText 把 HRESULT 写成「0x88890008 AUDCLNT_E_UNSUPPORTED_FORMAT（不支持该采样格式）」，方便远程排查。
func HRText(code uint32) string {
	name, ok := hrNames[code]
	if !ok {
		switch {
		case code&0x80000000 == 0:
			name = "成功"
		case code>>16&0x7FF == 7: // FACILITY_WIN32
			name = fmt.Sprintf("Win32 错误 %d", code&0xFFFF)
		default:
			name = "未知错误"
		}
	}
	return fmt.Sprintf("0x%08X %s", code, name)
}

